def item(
    question: str,
    prose: str,
    quote_keys: list[str],
    *,
    section: str,
    case_type: str,
    label: int,
    tools: list[str],
    escalate: bool,
    critique: str,
    order_id: str | None = None,
    email: str | None = None,
    reason: str | None = None,
    eligibility_code: str | None = None,
) -> dict:
    quotes = [RULES[key] for key in quote_keys]
    expected = prose.strip()
    for quote in quotes:
        if quote not in expected:
            expected = f"{expected} {quote}"
    metadata = {
        "source": "support_handbook.md",
        "section": section,
        "case_type": case_type,
        "expected_tools": tools,
        "should_escalate": escalate,
        "quotes": quotes,
    }
    if order_id:
        metadata["order_id"] = order_id
        metadata["email"] = email
        metadata["reason"] = reason
        metadata["eligibility_code"] = eligibility_code
    return {
        "input": question,
        "expected_output": expected,
        "metadata": metadata,
        "label": label,
        "critique": critique,
    }


